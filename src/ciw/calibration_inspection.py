"""Bounded DCC inspection and declared Link applicability, never calibration approval.

Only the PTB DCC 3.3.0 UTF-8 structural/scalar inspection profile is supported.
This is deliberately not an XSD validator, XML-signature verifier or correction
loader. The original certificate, operator mapping and observation stay distinct.
"""
from __future__ import annotations

import argparse
from copy import deepcopy
from decimal import Decimal, InvalidOperation
from io import StringIO
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET

from . import link_contract as c
from .calibration_status import _timestamp
from .link_gateway import calibration_declaration
from .session import loads_json

MAX_CERTIFICATE = 1024 * 1024
PROFILE = "ncp.dcc-3.3.0-scalar-inspection.v1"
DCC = "{https://ptb.de/dcc}"
SI = "{https://ptb.de/si}"
DS = "{http://www.w3.org/2000/09/xmldsig#}"
SCHEMA_SOURCE = "https://www.ptb.de/dcc/v3.3.0/autogenerated-docs/dcc_xsd.html"


def _decimal(value):
    if (type(value) is not str or len(value) > 128
            or re.fullmatch(r"[+-]?(?:[0-9]+(?:\.[0-9]*)?|\.[0-9]+)(?:[eE][+-]?[0-9]+)?", value) is None):
        raise ValueError("Require bounded decimal spelling")
    try:
        result = Decimal(value)
    except InvalidOperation as exc:
        raise ValueError("Invalid decimal") from exc
    if not result.is_finite() or abs(result.adjusted()) > 10000:
        raise ValueError("Decimal exceeds inspection profile")
    return result


def _text(element, path, *, required=False):
    found = element.findall(path)
    if len(found) > 1 or (required and len(found) != 1):
        raise ValueError("Missing or ambiguous certificate field")
    if not found:
        return None
    value = found[0].text
    if list(found[0]) or value is None or not value.strip() or len(value) > 512:
        raise ValueError("Require bounded simple certificate field")
    return value.strip()


def _parse(raw):
    # No DTD/entity/network/schema-location processing. UTF-8 only makes the
    # explicit declaration rejection independent of a hidden alternate encoding.
    text = raw.decode("utf-8-sig")
    if "\x00" in text or re.search(r"<!\s*(?:DOCTYPE|ENTITY)", text, re.I):
        raise ValueError("DTD and entity declarations are outside this profile")
    declaration = re.match(r"\s*<\?xml\s+[^?]*encoding\s*=\s*['\"]([^'\"]+)", text, re.I)
    if declaration and declaration[1].lower().replace("_", "-") not in {"utf-8", "utf8"}:
        raise ValueError("Only UTF-8 certificate bytes are supported")
    parser = ET.iterparse(StringIO(text), events=("start", "end"))
    depth, count = 0, 0
    for event, element in parser:
        if event == "start":
            depth += 1
            count += 1
            if depth > 32 or count > 10000 or len(element.attrib) > 32:
                raise ValueError("Certificate XML exceeds inspection budget")
        else:
            depth -= 1
    return parser.root


def inspect_certificate(raw: bytes) -> dict:
    """Inspect exact bytes without fetching schemas, following links or trusting signatures."""
    if type(raw) is not bytes or not 0 < len(raw) <= MAX_CERTIFICATE:
        raise ValueError("Require nonempty certificate bytes within 1 MiB")
    report = {"schema": "ncp.calibration-inspection.v1", "profile": PROFILE,
        "source": {"sha256": c.bytes_ref(raw), "byte_count": len(raw)},
        "parse": {"status": "FAILED"},
        "schema_inspection": {"status": "NOT_INSPECTED", "full_xsd_validation": "not_performed",
                              "schema_source": SCHEMA_SOURCE},
        "issuer_authenticity": {"status": "UNKNOWN", "signature_verification": "not_performed"},
        "applicability": {"status": "UNKNOWN", "reason": "no_bound_operator_scope_and_observation"},
        "correction_authorization": {"status": "NOT_GRANTED", "correction_applied": False},
        "facts": None, "physical_qualification": "not_established"}
    try:
        root = _parse(raw)
    except (UnicodeError, ET.ParseError, ValueError) as exc:
        report["parse"]["reason"] = str(exc)[:512]
        return report
    report["parse"] = {"status": "PARSED"}
    report["issuer_authenticity"]["signature_elements"] = len(root.findall(DS + "Signature"))
    report["schema_inspection"].update(namespace=root.tag, declared_version=root.get("schemaVersion"))
    if root.tag != DCC + "digitalCalibrationCertificate" or root.get("schemaVersion") != "3.3.0":
        report["schema_inspection"]["status"] = "UNSUPPORTED_PROFILE"
        return report
    try:
        ids = [node.get("id") for node in root.iter() if node.get("id") is not None]
        if len(ids) != len(set(ids)) or any(not item or len(item) > 128 for item in ids):
            raise ValueError("Duplicate, empty or oversized XML ID")
        id_set = set(ids)
        for node in root.iter():
            if any(ref not in id_set for ref in node.get("refId", "").split()):
                raise ValueError("Unresolved XML ID reference")
        administrative = root.findall(DCC + "administrativeData")
        measurements = root.findall(DCC + "measurementResults")
        if len(administrative) != 1 or len(measurements) != 1:
            raise ValueError("Require one administrativeData and measurementResults")
        administrative = administrative[0]
        core = administrative.findall(DCC + "coreData")
        if len(core) != 1:
            raise ValueError("Require one coreData")
        identifier = _text(core[0], DCC + "uniqueIdentifier", required=True)
        items = []
        for item in administrative.findall(DCC + "items/" + DCC + "item"):
            identities = [{"issuer": _text(identity, DCC + "issuer", required=True),
                           "value": _text(identity, DCC + "value", required=True)}
                          for identity in item.findall(DCC + "identifications/" + DCC + "identification")]
            if any(identity["issuer"] not in {"manufacturer", "calibrationLaboratory", "customer", "owner", "other"}
                   for identity in identities):
                raise ValueError("Unsupported identification issuer")
            items.append({"xml_id": item.get("id"), "identifications": identities})
        if not items or len(items) > 64:
            raise ValueError("Require 1..64 top-level calibration items")
        quantities, unsupported = [], 0
        for node in measurements[0].iter(DCC + "quantity"):
            real = node.findall(SI + "real")
            if len(real) != 1:
                unsupported += 1
                continue
            value = _text(real[0], SI + "value", required=True)
            unit = _text(real[0], SI + "unit", required=True)
            _decimal(value)
            quantities.append({"xml_id": node.get("id"), "ref_ids": node.get("refId", "").split(),
                               "value_text": value, "unit_text": unit})
        if len(quantities) > 1024:
            raise ValueError("Too many scalar quantities")
        report["facts"] = {"certificate_id": identifier, "items": items, "scalar_quantities": quantities,
            "unsupported_quantity_count": unsupported,
            "calibration_period": {field: _text(core[0], DCC + field) for field in
                ("beginPerformanceDate", "endPerformanceDate", "issueDate")},
            "range_and_recalibration_interval": "not_inferred_from_calibration_points_or_dates"}
        report["schema_inspection"]["status"] = "INSPECTION_PROFILE_PASSED"
    except ValueError as exc:
        report["schema_inspection"].update(status="INSPECTION_PROFILE_FAILED", reason=str(exc))
    return report


def inspect_link_calibration(declaration, *, device, observation, scope=None) -> dict:
    """Check existing Link declaration plus optional explicitly declared scalar scope.

    The scope is operator interpretation, not certificate-originated authority.
    It binds XML item/quantity IDs to a Link channel and a declared inclusive range.
    No unit conversion, correction extraction, interval inference or grant occurs.
    """
    calibration_declaration(declaration)
    device = c.manifest(device)
    c.validate_observation(observation, device)
    raw = c.unpack(declaration["certificate"], 32768)
    report = inspect_certificate(raw)
    report["declaration_ref"] = c.content_identity(declaration)
    report["observation_id"] = observation["measurement_id"]
    checks = []

    def check(name, value, reason):
        checks.append({"check": name, "status": "UNKNOWN" if value is None else "MATCH" if value else "MISMATCH",
                       "basis": reason})

    channel = c.channel_for(device, observation["channel_id"])
    check("declaration_reference", observation["calibration_ref"] == c.content_identity(declaration), "exact retained declaration identity")
    check("configuration", declaration["manifest_ref"] == c.content_identity(device), "exact manifest binding")
    check("channel", declaration["channel_id"] == channel["id"], "declaration channel")
    check("unit", declaration["unit"] == channel["unit"], "exact unit token; no implicit conversion")
    at = observation["acquired_at"]
    in_time = None if at is None else (_timestamp(declaration["valid_from"], "valid_from", strict=True)
        <= _timestamp(at, "acquired_at", strict=True) < _timestamp(declaration["valid_until"], "valid_until", strict=True))
    check("acquisition_interval", in_time, "operator declared half-open interval; receipt time is not acquisition time")
    if scope is None or report["facts"] is None:
        for name in ("instrument", "certificate_quantity", "quantity_item_association", "range"):
            check(name, None, "no supported certificate and exact operator scope")
    else:
        c.bounded(scope, 16384)
        c.keys(scope, {"schema", "certificate_ref", "item_xml_id", "identification_issuer", "quantity_xml_id",
                       "channel_id", "certificate_unit", "link_unit", "range", "interpretation_basis"})
        if scope["schema"] != "ncp.dcc-link-scalar-scope.v1":
            raise ValueError("Unsupported scalar certificate scope")
        c.content_ref(scope["certificate_ref"])
        for key in ("item_xml_id", "identification_issuer", "quantity_xml_id", "channel_id", "certificate_unit", "link_unit", "interpretation_basis"):
            c.text(scope[key], maximum=512)
        c.keys(scope["range"], {"minimum", "maximum"})
        low, high = _decimal(scope["range"]["minimum"]), _decimal(scope["range"]["maximum"])
        if low > high:
            raise ValueError("Scope range is inverted")
        check("scope_certificate", scope["certificate_ref"] == c.bytes_ref(raw), "exact certificate bytes")
        check("scope_channel", scope["channel_id"] == channel["id"], "operator mapping; not an authenticated DCC channel claim")
        check("scope_link_unit", scope["link_unit"] == channel["unit"], "operator declares certificate-to-Link unit equivalence")
        items = [item for item in report["facts"]["items"] if item["xml_id"] == scope["item_xml_id"]]
        identities = [] if not items else [identity["value"] for identity in items[0]["identifications"]
                                         if identity["issuer"] == scope["identification_issuer"]]
        check("instrument", None if not identities else device["instrument_id"] in identities,
              "exact instrument identity under declared issuer; item XML ID alone is not instrument identity")
        quantities = [item for item in report["facts"]["scalar_quantities"] if item["xml_id"] == scope["quantity_xml_id"]]
        check("certificate_quantity", bool(quantities) and quantities[0]["unit_text"] == scope["certificate_unit"],
              "selected scalar XML quantity and exact certificate unit spelling")
        references = quantities[0]["ref_ids"] if quantities else []
        check("quantity_item_association", None if not references else scope["item_xml_id"] in references,
              "selected scalar quantity must explicitly reference the selected certificate item; no implicit association")
        # Range is operator-declared, never the min/max of certificate points.
        value = observation["value"]
        spelling = (c.unpack(observation["raw"]).decode("ascii").split(" ")[0]
                    if value is not None and observation["stage"] == "reported"
                    and channel["encoding"] == "notation-ascii-scalar.v1" else str(value))
        check("range", None if value is None else low <= _decimal(spelling) <= high,
              "inclusive operator-declared applicability range in Link units")
        report["scope"] = {"ref": c.content_identity(scope), "declaration": deepcopy(scope), "authority": "operator_declared_only"}
    statuses = {item["status"] for item in checks}
    report["applicability"] = {"status": "MISMATCH" if "MISMATCH" in statuses else "UNKNOWN" if "UNKNOWN" in statuses
                             else "MATCHES_DECLARED_SCOPE", "checks": checks,
                             "chain_applicability": "not_established_by_declared_scope_match"}
    return report


def _read(path, limit):
    path = Path(path)
    if path.is_symlink() or not path.is_file():
        raise ValueError("Require a regular input file")
    with path.open("rb") as stream:
        raw = stream.read(limit + 1)
    if not raw or len(raw) > limit:
        raise ValueError("Input exceeds byte budget")
    return raw


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("certificate", help="UTF-8 DCC XML; inspection does not authenticate the issuer")
    parser.add_argument("--output", required=True, help="New retention directory for exact source and report")
    parser.add_argument("--link-context", help="JSON containing declaration, device, observation and optional-null scope")
    args = parser.parse_args(argv)
    raw = _read(args.certificate, MAX_CERTIFICATE)
    context_bytes = None
    if args.link_context:
        context_bytes = _read(args.link_context, 131072)
        context = loads_json(context_bytes.decode("utf-8"))
        c.keys(context, {"declaration", "device", "observation", "scope"})
        calibration_declaration(context["declaration"])
        if c.unpack(context["declaration"]["certificate"], 32768) != raw:
            raise ValueError("Context declaration certificate differs from exact input bytes")
        report = inspect_link_calibration(context["declaration"], device=context["device"],
            observation=context["observation"], scope=context["scope"])
        report["context_source"] = {"sha256": c.bytes_ref(context_bytes), "byte_count": len(context_bytes)}
    else:
        report = inspect_certificate(raw)
    output = Path(args.output)
    output.mkdir(exist_ok=False)
    (output / "certificate.xml").write_bytes(raw)
    if context_bytes is not None:
        (output / "context.json").write_bytes(context_bytes)
    (output / "inspection.json").write_text(json.dumps(report, indent=2, ensure_ascii=True) + "\n", encoding="utf-8")
    print(json.dumps(report, ensure_ascii=True))
    return 0 if (report["schema_inspection"]["status"] == "INSPECTION_PROFILE_PASSED"
                 and report["applicability"]["status"] != "MISMATCH") else 2


if __name__ == "__main__":
    raise SystemExit(main())
