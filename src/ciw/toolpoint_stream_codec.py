"""Lossless storage deltas for existing QC journal updates.

Storage representation only: no unit conversion, evaluator or content-ID change.
Each reconstructed native update must match its original full content identity.
"""
from __future__ import annotations

from copy import deepcopy
import json

from .core.identities import canonical_json, content_identity
from .manufacturing_contracts import MAX_BYTES, bounded, count, items, keys, ref, text, _float, _pairs
from .toolpoint_stream import LEGACY, NATIVE, UPDATE_SCHEMA

DELTA_SCHEMA = "ciw.toolpoint-stream-storage-delta.v1"
UPDATE_FIELDS = {"schema", "sequence", "previous_receipt_ref", "received_at_s", "final", "observation"}


def dumps(value: dict) -> str:
    bounded(value)
    return canonical_json(value)


def loads(raw: str) -> dict:
    """Accept only bounded canonical JSON generated by the existing NET encoder."""
    if type(raw) is not str or len(raw.encode("utf-8")) > MAX_BYTES:
        raise ValueError("Invalid or oversized stored JSON")
    def invalid(token):
        raise ValueError("Nonfinite stored number")
    value = json.loads(raw, object_pairs_hook=_pairs, parse_float=_float, parse_constant=invalid)
    bounded(value)
    if type(value) is not dict or canonical_json(value) != raw:
        raise ValueError("Stored JSON is not the exact canonical representation")
    return value


def _channel_field(profile: str) -> str:
    if profile == LEGACY:
        return "streams"
    if profile == NATIVE:
        return "signals"
    raise ValueError("Unsupported delta profile")


def _channels(update: dict, field: str) -> dict:
    keys(update, UPDATE_FIELDS)
    if update["schema"] != UPDATE_SCHEMA:
        raise ValueError("Wrong native update schema")
    result = {}
    for channel in items(update["observation"][field], maximum=32):
        sid = text(channel["sensor_id"])
        if sid in result:
            raise ValueError("Duplicate sensor in delta input")
        items(channel["samples"], maximum=2048)
        result[sid] = channel
    return result


def encode(previous: dict | None, update: dict, *, profile: str) -> dict:
    """Encode an already admitted cumulative update without repeating old samples."""
    bounded(update)
    field = _channel_field(profile)
    current = _channels(update, field)
    old = {} if previous is None else _channels(previous, field)
    if not set(old).issubset(current):
        raise ValueError("Storage delta cannot remove a sensor")
    channels = []
    for sid, channel in current.items():
        before = old[sid]["samples"] if sid in old else []
        samples = channel["samples"]
        if len(samples) < len(before) or content_identity(samples[:len(before)]) != content_identity(before):
            raise ValueError("Storage delta cannot rewrite accepted samples")
        channels.append({"metadata": deepcopy({k: v for k, v in channel.items() if k != "samples"}),
                         "prior_count": len(before), "samples": deepcopy(samples[len(before):])})
    delta = {"schema": DELTA_SCHEMA, "profile": profile,
             "previous_update_ref": None if previous is None else content_identity(previous),
             "update_ref": content_identity(update),
             "update_header": deepcopy({k: v for k, v in update.items() if k != "observation"}),
             "observation_header": deepcopy({k: v for k, v in update["observation"].items() if k != field}),
             "channels": channels}
    bounded(delta)
    return delta


def decode(previous: dict | None, delta: dict, *, profile: str) -> dict:
    """Reconstruct exact native bytes and refuse stale, missing or corrupt deltas."""
    bounded(delta)
    keys(delta, {"schema", "profile", "previous_update_ref", "update_ref", "update_header",
                 "observation_header", "channels"})
    field = _channel_field(profile)
    if delta["schema"] != DELTA_SCHEMA or delta["profile"] != profile:
        raise ValueError("Wrong delta schema or profile")
    if delta["previous_update_ref"] != (None if previous is None else content_identity(previous)):
        raise ValueError("Storage delta binds a different previous update")
    ref(delta["update_ref"])
    keys(delta["update_header"], UPDATE_FIELDS - {"observation"})
    if type(delta["observation_header"]) is not dict or field in delta["observation_header"]:
        raise ValueError("Invalid stored observation header")
    old = {} if previous is None else _channels(previous, field)
    channels, seen = [], set()
    for row in items(delta["channels"], maximum=32):
        keys(row, {"metadata", "prior_count", "samples"})
        metadata = row["metadata"]
        if type(metadata) is not dict or "samples" in metadata:
            raise ValueError("Invalid stored channel metadata")
        sid = text(metadata["sensor_id"])
        if sid in seen:
            raise ValueError("Duplicate stored channel")
        seen.add(sid)
        prior = old[sid]["samples"] if sid in old else []
        count(row["prior_count"], minimum=0, maximum=2048)
        if row["prior_count"] != len(prior):
            raise ValueError("Storage delta sample offset mismatch")
        added = items(row["samples"], maximum=2048)
        if len(prior) + len(added) > 2048:
            raise ValueError("Storage delta reconstruction exceeds sample budget")
        channels.append({**deepcopy(metadata), "samples": deepcopy(prior + added)})
    if not set(old).issubset(seen):
        raise ValueError("Storage delta lost a prior sensor")
    update = {**deepcopy(delta["update_header"]),
              "observation": {**deepcopy(delta["observation_header"]), field: channels}}
    bounded(update)
    if content_identity(update) != delta["update_ref"]:
        raise ValueError("Reconstructed update content differs from admitted source")
    return update
